#!/usr/bin/env bash
# install.sh — runs INSIDE the extracted self-extracting installer.
# The build-installer.sh stages the source + this script + an extractor stub
# into a single .sh file. When that .sh is run, it extracts to a temp dir
# and invokes this script with WRITER_APP_PAYLOAD_DIR pointing at the source.
#
# Standalone usage (from a git checkout):
#   bash scripts/install.sh
#
# Env overrides:
#   WRITER_APP_PREFIX  install location (default ~/.local/share/writer-app)
#   WRITER_APP_BIN     where to put the `writer` shim (default ~/.local/bin)

set -euo pipefail

PREFIX="${WRITER_APP_PREFIX:-$HOME/.local/share/writer-app}"
BIN_DIR="${WRITER_APP_BIN:-$HOME/.local/bin}"
PAYLOAD="${WRITER_APP_PAYLOAD_DIR:-$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)}"

header() {
    echo
    echo "──────────────────────────────────────────────────────────"
    echo "  $1"
    echo "──────────────────────────────────────────────────────────"
}

err() {
    echo "✗ $1" >&2
    exit 1
}

# ── Preflight ────────────────────────────────────────────────────────────
header "writer-app installer"

# Python check
if ! command -v python3 >/dev/null 2>&1; then
    err "python3 is required but not found in PATH"
fi

PY_VERSION=$(python3 -c 'import sys; print("%d.%d" % sys.version_info[:2])')
PY_MAJOR=$(echo "$PY_VERSION" | cut -d. -f1)
PY_MINOR=$(echo "$PY_VERSION" | cut -d. -f2)
if [ "$PY_MAJOR" -lt 3 ] || { [ "$PY_MAJOR" -eq 3 ] && [ "$PY_MINOR" -lt 10 ]; }; then
    err "Python 3.10 or later is required (found $PY_VERSION)"
fi
echo "  ✓ Python $PY_VERSION"

# Ollama check (warn-only — the user might be using remote only)
if command -v ollama >/dev/null 2>&1; then
    echo "  ✓ Ollama is installed"
else
    cat <<EOF
  ⚠ Ollama not found in PATH.
    writer-app runs locally on Ollama by default. Install it from:
      https://ollama.com
    (Remote-only operation via Groq/Cerebras is supported, but you'll still
    benefit from having Ollama for offline fallback.)
EOF
fi

# ── Install ──────────────────────────────────────────────────────────────
header "Installing writer-app to $PREFIX"

mkdir -p "$PREFIX"
# Wipe any previous install but keep user data (~/books/, etc. are elsewhere)
rm -rf "$PREFIX"/src "$PREFIX"/ui "$PREFIX"/scripts "$PREFIX"/docs \
       "$PREFIX"/corpus "$PREFIX"/pyproject.toml "$PREFIX"/README.md \
       "$PREFIX"/LICENSE "$PREFIX"/.streamlit 2>/dev/null || true

# Copy payload
cp -R "$PAYLOAD"/src        "$PREFIX/"
cp -R "$PAYLOAD"/ui         "$PREFIX/"
cp -R "$PAYLOAD"/scripts    "$PREFIX/"
cp -R "$PAYLOAD"/docs       "$PREFIX/" 2>/dev/null || true
cp -R "$PAYLOAD"/corpus     "$PREFIX/" 2>/dev/null || true
cp -R "$PAYLOAD"/.streamlit "$PREFIX/" 2>/dev/null || true
cp    "$PAYLOAD"/pyproject.toml "$PREFIX/"
cp    "$PAYLOAD"/README.md      "$PREFIX/"
cp    "$PAYLOAD"/LICENSE        "$PREFIX/"

echo "  ✓ Source extracted"

# ── Shim ─────────────────────────────────────────────────────────────────
header "Creating launcher at $BIN_DIR/writer"

mkdir -p "$BIN_DIR"
cat > "$BIN_DIR/writer" <<EOF
#!/usr/bin/env bash
# writer launcher — generated by writer-app installer
exec python3 -c "import sys; sys.path.insert(0, '$PREFIX/src'); from writer_app.cli import main; main()" "\$@"
EOF
chmod +x "$BIN_DIR/writer"
echo "  ✓ writer launcher created"

# PATH check
case ":$PATH:" in
    *":$BIN_DIR:"*)
        echo "  ✓ $BIN_DIR already in PATH"
        ;;
    *)
        echo
        echo "  ⚠ $BIN_DIR is NOT in your PATH."
        echo "    Add this to your ~/.zshrc or ~/.bashrc:"
        echo "      export PATH=\"$BIN_DIR:\$PATH\""
        echo
        ;;
esac

# ── Corpus ───────────────────────────────────────────────────────────────
header "Setting up corpus"

CORPUS_USER="$HOME/.local/share/writer-app/corpus"
mkdir -p "$CORPUS_USER/style_cards" "$CORPUS_USER/craft" "$CORPUS_USER/gutenberg"

# Copy bundled style cards + craft notes (Gutenberg downloads on demand)
if [ -d "$PAYLOAD/corpus/style_cards" ]; then
    cp -R "$PAYLOAD"/corpus/style_cards/* "$CORPUS_USER/style_cards/" 2>/dev/null || true
fi
if [ -d "$PAYLOAD/corpus/craft" ]; then
    cp -R "$PAYLOAD"/corpus/craft/* "$CORPUS_USER/craft/" 2>/dev/null || true
fi
echo "  ✓ Style cards + craft notes copied to $CORPUS_USER"
echo "    Run 'writer corpus' later to download the Gutenberg classics."

# ── Done ─────────────────────────────────────────────────────────────────
header "Installation complete"

cat <<EOF

  writer-app is installed at: $PREFIX
  Launcher:                   $BIN_DIR/writer

  Next steps:
    1. (Optional) pull Ollama models:
         ollama pull qwen2.5:7b           # judge (fast)
         ollama pull mistral-nemo:12b     # draft (best local prose)
    2. Verify the install:
         writer --help
         writer providers
    3. Initialise your first project:
         writer init "My Series" --author "Real Name" --pen-name "Pen Name"
    4. Or launch the interactive UI:
         pip install streamlit
         writer ui

  Uninstall: $PREFIX/scripts/uninstall.sh

  Docs: https://github.com/Thandv/writer-app/tree/main/docs

EOF
